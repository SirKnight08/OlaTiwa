export const recipes = raw.map(toRecipe);

export const getFeaturedRecipes = () => recipes.filter((recipe) => recipe.featured);

export const getPopularRecipes = () => recipes.filter((recipe) => recipe.popular);

export const getRecipesByCategory = (category: string) =>
  recipes.filter((recipe) => recipe.category.toLowerCase() === category.toLowerCase());

export const searchRecipes = (query: string) => {
  const normalized = query.trim().toLowerCase();
  if (!normalized) return recipes;

  return recipes.filter((recipe) => {
    const searchable = [
      recipe.title,
      recipe.category,
      recipe.cuisine,
      recipe.description,
      ...recipe.tags,
      ...recipe.ingredients.map((ingredient) => ingredient.name),
    ]
      .join(' ')
      .toLowerCase();

    return searchable.includes(normalized);
  });
};
