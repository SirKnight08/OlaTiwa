import type { Recipe } from './types';

type Difficulty = 'Easy' | 'Medium' | 'Hard';

type CompactRecipe = {
  id: string;
  t: string;
  d: string;
  cat: string;
  cu: string;
  img: string;
  pt: number;
  ct: number;
  tt: number;
  diff: Difficulty;
  srv: number;
  feat: boolean;
  pop: boolean;
  tips?: string;
  ing: [string, number, string][];
  steps: [string, number?][];
  tags: string[];
};

function toRecipe(r: CompactRecipe): Recipe {
  return {
    id: r.id,
    title: r.t,
    description: r.d,
    category: r.cat,
    cuisine: r.cu,
    image: r.img,
    preparationTime: r.pt,
    cookingTime: r.ct,
    totalTime: r.tt,
    difficulty: r.diff,
    servings: r.srv,
    ingredients: r.ing.map(([name, qty, unit], idx) => ({
      id: `${r.id}-ing-${idx}`,
      name,
      quantity: qty,
      unit,
    })),
    steps: r.steps.map(([instruction, duration], idx) => ({
      id: `${r.id}-step-${idx}`,
      instruction,
      duration: duration ?? 0,
    })),
    tags: r.tags,
    featured: r.feat,
    popular: r.pop,
    tips: r.tips,
  };
}

